function define(
  id: string,
  name: string,
  family: PolicyFamily,
  summary: string,
  cost: [number, number],
  quarters: number,
  difficulty: number,
  capacity: number,
  mechanism: string,
  tradeoffs: string[],
  effects: PolicyDefinition['effects'],
  legalRoute = 'Cabinet programme within an approved parliamentary appropriation',
  evidenceIds: string[] = [],
): PolicyDefinition {
  return {
    id,
    name,
    family,
    summary,
    legalRoute,
    setupCost: cost[0],
    recurringCost: cost[1],
    implementationQuarters: quarters,
    approvalDifficulty: difficulty,
    capacityRequired: capacity,
    mechanism,
    tradeoffs,
    benefits: [summary],
    effects,
    evidenceIds: [
      ...new Set([
        'constitution-finance',
        ...evidenceIds,
        ...(family === 'institutions'
          ? ['ppa-act', 'constitution-judiciary']
          : family === 'agriculture'
            ? ['constitution-land', 'cocobod-ched']
            : family === 'public-finances'
              ? ['constitution-legislature']
              : ['ppa-act']),
      ]),
    ],
    assumptions: [
      ...assumptions,
      'Linked institutional and mechanism sources do not validate the illustrative effect coefficients. A causal Ghana estimate for this exact policy configuration is unavailable.',
    ],
  };
}
